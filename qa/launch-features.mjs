import assert from 'node:assert/strict'
import { execFileSync } from 'node:child_process'
import path from 'node:path'
import { chromium } from 'playwright'
import { mkdir, readFile } from 'node:fs/promises'
const base = process.env.QA_BASE_URL || 'http://127.0.0.1:4191'
const out = process.env.QA_OUT_DIR || 'artifacts/launch-features'
await mkdir(out, { recursive: true })
const clip = path.resolve(out, 'test-clip.mp4')
const longClip = path.resolve(out, 'too-long.mp4')
for (const [file, seconds] of [[clip, '2'], [longClip, '31']]) execFileSync('ffmpeg', ['-y', '-f', 'lavfi', '-i', 'color=c=coral:s=160x120:r=10', '-t', seconds, '-an', '-c:v', 'libx264', '-pix_fmt', 'yuv420p', file], { stdio: 'ignore' })
const browser = await chromium.launch({ executablePath: process.env.QA_BROWSER_PATH || '/usr/bin/chromium', headless: true })
const context = await browser.newContext({ viewport: { width: 393, height: 852 }, permissions: ['geolocation'], geolocation: { latitude: 32.7, longitude: -117.1, accuracy: 5 } })
const page = await context.newPage()
const errors = []; page.on('pageerror', error => errors.push(error.message))
try {
  await page.goto(`${base}/demo/app`)
  await page.locator('.bnav').getByRole('button', { name: 'Pack', exact: true }).click()
  await page.getByRole('button', { name: 'Edit Bailey', exact: true }).click()
  await page.getByRole('button', { name: 'Use Poodle avatar for Bailey', exact: true }).click()
  await page.getByRole('status').filter({ hasText: 'avatar saved' }).waitFor()
  assert.equal(await page.locator('.profile-dog-card--editing .profile-dog-avatar-emoji').innerText(), '🐩')
  await page.getByLabel("Upload Bailey's avatar", { exact: true }).setInputFiles({ name: 'avatar.png', mimeType: 'image/png', buffer: Buffer.from('iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAQAAAC1HAwCAAAAC0lEQVR42mP8/x8AAwMCAO+jRZkAAAAASUVORK5CYII=', 'base64') })
  await page.locator('.profile-dog-card--editing .profile-dog-avatar-img').waitFor()
  await page.screenshot({ path: `${out}/avatar-photo.png` })
  await page.reload()
  await page.locator('.bnav').getByRole('button', { name: 'Pack', exact: true }).click()
  assert.ok(await page.locator('.profile-dog-avatar-img').count())
  await page.getByRole('button', { name: 'Edit Bailey', exact: true }).click()
  await page.getByRole('button', { name: 'Use Paw prints avatar for Bailey', exact: true }).click()
  await page.getByRole('status').filter({ hasText: 'avatar saved' }).waitFor()
  assert.equal(await page.locator('.profile-dog-card--editing .profile-dog-avatar-img').count(), 0)
  await page.getByRole('button', { name: 'Cancel', exact: true }).click()
  await page.locator('.bnav').getByRole('button', { name: 'Today', exact: true }).click()
  await page.getByRole('button', { name: 'Start a walk', exact: true }).click()
  const start = page.getByRole('button', { name: 'Start adventure', exact: true }); if (await start.isVisible()) await start.click()
  await page.getByRole('button', { name: 'Record phone GPS route', exact: true }).click()
  await page.waitForFunction(() => JSON.parse(localStorage.getItem('pawstreak:demo')).activeAdventure?.routePoints?.length >= 1)
  await page.getByRole('button', { name: 'Pause', exact: true }).click()
  await page.getByRole('status').filter({ hasText: 'Route recording paused' }).waitFor()
  await page.getByRole('button', { name: 'Resume', exact: true }).click()
  await page.getByRole('button', { name: 'Stop route recording', exact: true }).click()
  await page.getByRole('button', { name: 'Finish walk', exact: true }).click()
  await page.locator('.memory-video').waitFor()
  await page.locator('.memory-video input').setInputFiles(clip)
  await page.locator('.memory-video [role=status]').filter({ hasText: 'Video saved.' }).waitFor()
  const video = page.locator('.memory-video video')
  await video.evaluate(el => el.play())
  await page.waitForFunction(() => document.querySelector('.memory-video video')?.currentTime > 0)
  await page.screenshot({ path: `${out}/recap-video.png`, fullPage: true })
  const selected = await page.evaluate(() => JSON.parse(localStorage.getItem('pawstreak:demo')).selectedJourneyEntryId)
  await page.reload()
  await page.locator('.bnav').getByRole('button', { name: 'Journey', exact: true }).click()
  await page.locator(`[data-memory-id="${selected}"]`).click()
  await page.locator('.memory-video video').waitFor()
  assert.ok(await page.evaluate(id => JSON.parse(localStorage.getItem('pawstreak:demo')).journeyEntries.find(e => e.id === id).routePoints.length > 0, selected))
  assert.equal(await page.evaluate(() => JSON.parse(localStorage.getItem('pawstreak:demo')).selectedJourneyEntryId), selected)
  await page.getByRole('button', { name: 'Remove video', exact: true }).click()
  await page.locator('.memory-video [role=status]').filter({ hasText: 'Video removed.' }).waitFor()
  await page.locator('.memory-video input').setInputFiles({ name: 'not-video.txt', mimeType: 'text/plain', buffer: Buffer.from('not a video') })
  await page.locator('.memory-video [role=status]').filter({ hasText: 'Choose an MP4' }).waitFor()
  assert.equal(await page.locator('.memory-video video').count(), 0)
  await page.locator('.memory-video input').setInputFiles(longClip)
  await page.locator('.memory-video [role=status]').filter({ hasText: 'up to 30 seconds' }).waitFor()
  const downloadPromise = page.waitForEvent('download')
  await page.evaluate(async () => { const { downloadScheduledAdventureCalendar } = await import('/src/lib/calendarExport.ts'); await downloadScheduledAdventureCalendar({ title: 'Test walk', scheduledFor: '2026-12-01T17:00:00Z', locationLabel: 'Park', notes: '' }, 'Bailey') })
  const download = await downloadPromise
  const calendar = await readFile(await download.path(), 'utf8')
  assert.ok(calendar.includes('DTSTART:20261201T170000Z'))
  assert.ok(calendar.includes('BEGIN:VALARM'))
  await page.evaluate(async () => { const { clearDemoState } = await import('/src/lib/storage.ts'); clearDemoState() })
  await page.waitForFunction(async () => !(await indexedDB.databases()).some(db => db.name === 'pawstreak-demo-media'))
  assert.deepEqual(errors, [])
  console.log('PASS: avatar choice/photo/reload, GPS consent/pause, video select/play/reload/remove/invalid-file, real calendar download')
} finally { await browser.close() }
